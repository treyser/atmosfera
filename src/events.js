// Тепло чи холодно: за регіонами точок, між якими пливемо
const COLD = new Set(["north", "east"]);
const WARM = new Set(["center", "south"]);

export function eventsFor(from, to) {
  const rs = [from?.r, to?.r].filter(Boolean);
  const cold = rs.some((r) => COLD.has(r));
  const warm = rs.some((r) => WARM.has(r));
  return EVENTS.filter((e) => (!e.cold || cold) && (!e.warm || warm));
}

