export function rumors() {
  const list = read(RUMORS, null);
  if (list) return list;
  const s = SEED.map(([text, who, truth], i) => ({ id: "s" + i, text, who, where: "", truth, heard: false, verdict: "", votes: {}, at: 0 }));
  write(RUMORS, s);
  return s;
}
export const saveRumors = (l) => write(RUMORS, l);
export const heard = (room) => read(HEARD(room), []);
export const saveHeard = (room, l) => write(HEARD(room), l);

