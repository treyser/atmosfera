// Днів у морі між двома точками (мапа 1402 × 1122 пікселів; ~90 пікселів — день шляху)
export function daysBetween(a, b) {
  if (!a || !b) return 1;
  const dx = (a.u - b.u) * 1402;
  const dy = (a.v - b.v) * 1122;
  return Math.max(1, Math.round(Math.hypot(dx, dy) / 90));
}

