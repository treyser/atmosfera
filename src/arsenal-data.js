export const ARSENAL = W.map(([id, group, rarity, name, dmg, props, weight, price, desc, mech, quote]) => ({
  id, group, rarity, name, dmg, props, weight, price, desc, mech, quote, img: `${ART}${id}.webp`,
}));
export const weapon = (id) => ARSENAL.find((w) => w.id === id) ?? null;
export const isSecret = (w) => w.rarity !== "common";

// що відкрито гравцям у цій кімнаті (у майстра) і що бачить гравець
export const OPEN = (room) => `atmosfera.arsenal-open.${room}`;
export const SEEN = (room) => `atmosfera.arsenal-seen.${room}`;
export const opened = (room) => local(OPEN(room), []);
export const saveOpened = (room, ids) => saveLocal(OPEN(room), ids);
export const seen = (room) => local(SEEN(room), []);
export const saveSeen = (room, ids) => saveLocal(SEEN(room), ids);

export const gp = (n) => (n ? `${n.toLocaleString("uk-UA")} зм` : "безцінна");
export const FOCUS = "atmosfera.arsenal-focus";   // у гравця: яку картку відкрити (майстер показав)

// запис у лист персонажа
export const gearOf = (w) => ({ name: w.name, desc: `${w.dmg}; ${w.props}.`, mech: w.mech || "" });
