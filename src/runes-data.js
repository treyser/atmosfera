// Розбити текст на слова й знаки: { g: руна, l: літера } або { p: розділовий знак }
export function carve(text) {
  const words = [];
  for (const w of String(text ?? "").toLowerCase().replace(/[’ʼ`]/g, "'").split(/\s+/).filter(Boolean)) {
    words.push([...w].map((ch) => (ABC[ch] ? { g: ABC[ch], l: ch } : { p: ch })));
  }
  return words;
}
export const lettersIn = (text) => [...new Set([...String(text ?? "").toLowerCase()].filter((ch) => ABC[ch]))];

