// Знак руни: в'язана руна з перших літер її імені («Гострого Зуба» → ᚷ + ᛉ)
export function sigil(name) {
  const words = String(name).replace(/^Руна\s+/i, "").toLowerCase().split(/[\s'’ʼ-]+/).filter((w) => w.length > 1);
  const out = [];
  for (const w of words) { const g = ABC[w[0]]; if (g && !out.includes(g)) out.push(g); }
  return out.slice(0, 3);
}
export const short = (name) => String(name).replace(/^Руна\s+/i, "");

