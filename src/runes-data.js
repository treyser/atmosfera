// Що нового між двома станами — для сповіщень гравцям
export function news(prev, next) {
  const out = [];
  const who = next.ownerName || "Рунний коваль";
  for (const r of RUNES) {
    const a = prev.runes?.[r.id] ?? 0, b = next.runes?.[r.id] ?? 0;
    if (b > a) out.push(b === 1 ? `${who} відкриває «${r.name}»` : `«${r.name}» — ${TIERS[b].toLowerCase()} (${ROMAN[b]})`);
  }
  for (const k of CRAFT) if (next.craft?.[k.id] && !prev.craft?.[k.id]) out.push(`${who} знає ремісничу «${k.name}»`);
  const fresh = (next.letters ?? []).filter((l) => !(prev.letters ?? []).includes(l));
  if (fresh.length) out.push(`Розгадано ${fresh.length === 1 ? "руну" : "руни"}: ${fresh.map((l) => `${ABC[l]} = ${l.toUpperCase()}`).join(", ")}`);
  const had = new Set((prev.insc ?? []).map((i) => i.id));
  for (const i of next.insc ?? []) if (!had.has(i.id)) out.push(`Новий напис: «${i.title}»`);
  return out;
}
