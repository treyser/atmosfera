// ---------- сховища ----------
const read = (k, f) => { try { const r = localStorage.getItem(k); return r ? JSON.parse(r) : f; } catch { return f; } };
const write = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); return true; } catch { return false; } };

// майстер: усі написи (у браузері) і стан рун партії в цій кімнаті
export const INSC = "atmosfera.inscriptions";
export const STATE_KEY = (room) => `atmosfera.runes.${room}`;
export function inscriptions() {
  const list = read(INSC, null);
  if (list) return list;
  write(INSC, SAMPLE);
  return SAMPLE;
}
export const saveInscriptions = (list) => write(INSC, list);
const EMPTY = () => ({ runes: {}, craft: {}, letters: [], shown: [], owner: "", ownerName: "" });
export const runeState = (room) => ({ ...EMPTY(), ...read(STATE_KEY(room), {}) });
export const saveRuneState = (room, s) => write(STATE_KEY(room), s);

// що бачать гравці: стан + показані написи
export function packState(room) {
  const s = runeState(room);
  const insc = inscriptions().filter((i) => s.shown.includes(i.id)).map(({ id, title, where, text, rune }) => ({ id, title, where, text, rune }));
  return { runes: s.runes, craft: s.craft, letters: s.letters, owner: s.owner, ownerName: s.ownerName, insc };
}

