const pick = (a) => a[Math.floor(Math.random() * a.length)];
export const shout = (set, own = []) => pick(own.length && Math.random() < 0.7 ? own : L[set]?.shout ?? L.bazaar.shout);
export const mutter = (set, own = []) => pick(own.length && Math.random() < 0.6 ? own : L[set]?.mutter ?? L.bazaar.mutter);
// розмова двох: власні репліки NPC чергуються, інакше — готовий діалог із набору
export function talk(set, aOwn = [], bOwn = []) {
  if (aOwn.length && bOwn.length && Math.random() < 0.6) {
    const n = 2 + Math.floor(Math.random() * 3);
    return Array.from({ length: n }, (_, i) => pick(i % 2 ? bOwn : aOwn));
  }
  return pick(L[set]?.talk ?? L.bazaar.talk);
}
